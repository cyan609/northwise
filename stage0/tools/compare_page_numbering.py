#!/usr/bin/env python3
"""Stage 0 reconciliation: compare the regenerated page-number analysis (v2b)
against the archived v1 output, and record every changed count or status.

Why this exists
---------------
The v1 matcher (end-anchored footer regex) produced counts that were wrong in
both directions: false negatives on pages with trailing debris, false positives
from body text such as "S/STT/2". v2b replaces it. Because reports.json and
STAGE0_INVENTORY.md quote page-number figures, the change has to be auditable:
what moved, by how much, and why.

Inputs
------
  stage0/source-data/page_numbering.v1_end_anchored.json   (frozen v1 output)
  stage0/source-data/page_numbering.json                   (current v2b output)

Outputs
-------
  stage0/PAGE_NUMBERING_RECONCILIATION.md   human-readable diff table
  (stdout)                                  summary

This script never modifies either input.

Usage: python3 stage0/tools/compare_page_numbering.py
"""
import json
import os

ROOT = "/Users/chloeyan/workbuddy-ai/NORTHWISE"
SRC = os.path.join(ROOT, "stage0", "source-data")
V1 = os.path.join(SRC, "page_numbering.v1_end_anchored.json")
V2 = os.path.join(SRC, "page_numbering.json")
OUT = os.path.join(ROOT, "stage0", "PAGE_NUMBERING_RECONCILIATION.md")

REPORT_TITLES = {
    "AEIAR-276-2026": "Northern Metropolis Highway - San Tin Section",
    "AEIAR-271-2025": "Development at Ngau Tam Mei Area",
}


def forms_str(d):
    if not d:
        return "-"
    return ", ".join(f"{k} {v}" for k, v in sorted(d.items()))


def load():
    v1 = json.load(open(V1))
    v2 = json.load(open(V2))
    return v1, v2


def index_chapters(payload):
    return {c["filename"]: c for c in payload["chapters"]}


def diff_report(reg, p1, p2):
    """Return (rows, changed) for one report."""
    c1 = index_chapters(p1)
    c2 = index_chapters(p2)
    rows, changed = [], 0
    for fn in sorted(set(c1) | set(c2)):
        a, b = c1.get(fn), c2.get(fn)
        if a is None or b is None:
            rows.append({"filename": fn, "missing": "in v1" if a is None else "in v2b"})
            changed += 1
            continue
        d_folio = b["pages_with_folio"] - a["pages_with_folio"]
        d_cov = b["coverage"] - a["coverage"]
        forms_changed = a["forms"] != b["forms"]
        offset_changed = (a["offset_min"], a["offset_max"]) != (b["offset_min"], b["offset_max"])
        is_changed = bool(d_folio or forms_changed or offset_changed)
        if is_changed:
            changed += 1
        rows.append({
            "filename": fn,
            "pages": b["pages"],
            "v1_folio": a["pages_with_folio"],
            "v2_folio": b["pages_with_folio"],
            "d_folio": d_folio,
            "v1_cov": a["coverage"],
            "v2_cov": b["coverage"],
            "d_cov": round(d_cov, 3),
            "v1_forms": a["forms"],
            "v2_forms": b["forms"],
            "v1_offset": (a["offset_min"], a["offset_max"]),
            "v2_offset": (b["offset_min"], b["offset_max"]),
            "status_counts": b.get("status_counts"),
            "changed": is_changed,
        })
    return rows, changed


def main():
    v1, v2 = load()
    lines = [
        "# Stage 0 - page-number reconciliation (v1 -> v2c)",
        "",
        "Generated by `stage0/tools/compare_page_numbering.py`.",
        "",
        "**v1** = `page_numbering.v1_end_anchored.json` (frozen copy of the original",
        "end-anchored matcher). **v2c** = `page_numbering.json` (current matcher).",
        "",
        "Neither input is modified by this script. The v1 file is kept so these",
        "deltas stay reproducible.",
        "",
        "## What changed in the matcher",
        "",
        "| # | Defect in v1 | Effect | Fix in v2b |",
        "|---|---|---|---|",
        "| 1 | Footer regex anchored with `$` | Real folios on pages carrying a stray "
        "trailing character were reported missing (ch.4 pp.49/52/55 = `4-47`/`4-50`/`4-53`) "
        "| No end anchor; search the last 240 characters; last match wins |",
        "| 2 | No left boundary on the folio token | `S/STT/2 March 2026` in body text "
        "read as folio `2` (ch.1 p.4) | `(?<![\\w/\\-.])` before the token |",
        "| 3 | `chapter-roman` form unsupported | `15-i`/`15-ii` rejected, or matched "
        "as bare `i` | Own named group `\\d{1,2}-[ivxlcdm]{1,7}`, kept separate from "
        "`compound` so the form histogram stays truthful |",
        "| 4 | Report mode decided by mean of per-chapter coverage | Small chapters "
        "dominated: ch.15 (11 pp) and ch.13 (7 pp) dragged San Tin to `unverified` "
        "despite 86% of pages being numbered | Page-weighted coverage; both figures "
        "recorded |",
        "| 5 | Compound page part limited to `\\d{1,2}` | Chapters longer than 99 "
        "pages print three-digit folios (`8-100`, `10-137`, `9-113`). v1 read the "
        "`100` as a *plain* folio - right count, wrong label - and v2b's new left "
        "boundary rejected it, turning real folios into `absent` | Page part "
        "widened to `\\d{1,4}` |",
        "",
        "Regression gate: `stage0/tools/regression_page_numbers.py` (30 assertions,",
        "Cases A-D) must pass before this analysis is trusted.",
        "",
        "Defects 1, 2 and 5 were each found by a test or a diff, not by inspection:",
        "1 and 2 broke the Stage 1 extraction of ch.4 and ch.1, 5 showed up as the",
        "21/34/11 `plain -> absent` movements in the first reconciliation pass.",
        "",
    ]

    summary = {}
    for reg in ("AEIAR-276-2026", "AEIAR-271-2025"):
        p1 = v1["reports"][reg]
        p2 = v2["reports"][reg]
        rows, changed = diff_report(reg, p1, p2)
        count_changed = [r for r in rows if "missing" not in r and r["d_folio"]]
        form_only = [r for r in rows
                     if "missing" not in r and not r["d_folio"] and r["changed"]]
        summary[reg] = {
            "mode": (p1["page_numbering"], p2["page_numbering"]),
            "coverage": (p1.get("coverage_page_weighted"),
                         p2.get("coverage_page_weighted")),
            "changed_chapters": changed,
            "count_changed": len(count_changed),
        }

        lines += [
            f"## {reg} - {REPORT_TITLES.get(reg, '')}",
            "",
            f"- Report mode: **{p1['page_numbering']} -> {p2['page_numbering']}**",
            f"- Coverage (page-weighted): "
            f"{p1.get('coverage_page_weighted', 'not recorded in v1')} -> "
            f"{p2.get('coverage_page_weighted')}",
            f"- Coverage (mean of chapters, v2c only): "
            f"{p2.get('coverage_mean_of_chapters')}",
            "",
            f"**Chapters whose folio COUNT changed: {len(count_changed)}**"
            + (f" - {', '.join(r['filename'] for r in count_changed)}"
               if count_changed else " - none"),
            "",
        ]
        for r in count_changed:
            lines.append(f"- `{r['filename']}`: {r['v1_folio']} -> {r['v2_folio']} "
                         f"({r['d_folio']:+d})")
        if count_changed:
            lines.append("")
        lines += [
            f"Chapters where only the FORM LABEL changed: {len(form_only)} "
            f"(the count is identical; `roman` was previously used for the "
            f"chapter-roman form `15-i` and is now reported separately).",
            "",
            "| chapter | pages | folios v1 | folios v2c | delta | cov v1 | cov v2c "
            "| forms v1 | forms v2c | offset v1 | offset v2c |",
            "|---|---:|---:|---:|---:|---:|---:|---|---|---|---|",
        ]
        for r in rows:
            if "missing" in r:
                lines.append(f"| {r['filename']} | - | - | - | - | - | - | - | - | "
                             f"{r['missing']} | - |")
                continue
            mark = " **!**" if r["changed"] else ""
            lines.append(
                f"| {r['filename']}{mark} | {r['pages']} | {r['v1_folio']} | "
                f"{r['v2_folio']} | {r['d_folio']:+d} | {r['v1_cov']:.2f} | "
                f"{r['v2_cov']:.2f} | {forms_str(r['v1_forms'])} | "
                f"{forms_str(r['v2_forms'])} | {r['v1_offset']} | {r['v2_offset']} |")
        lines.append("")

        # pages now classified absent rather than unverified, where v1 had none
        newly_absent = [(r["filename"], r["status_counts"]["absent"])
                        for r in rows
                        if "missing" not in r and r["status_counts"]["absent"]]
        if newly_absent:
            lines += [
                "### Pages with a footer but no folio (status `absent`)",
                "",
                "v1 had no `absent` category: a page either matched a folio or was",
                "silently counted as unnumbered. v2c distinguishes a page that has the",
                "month-year footer but genuinely prints no folio from a page with no",
                "recognisable footer at all.",
                "",
                "| chapter | pages `absent` |",
                "|---|---:|",
            ]
            for fn, n in newly_absent:
                lines.append(f"| {fn} | {n} |")
            lines.append("")

    lines += [
        "## Sequence anomalies in the source PDFs",
        "",
        "Found by comparing per-page labels against the viewer index. Both are",
        "defects in the published PDFs, not in the matcher, and neither can be",
        "repaired by us.",
        "",
        "| chapter | anomaly | detail |",
        "|---|---|---|",
        "| `eia_ch10_out.pdf` | duplicate folio | Viewer pages 123 and 124 both print "
        "`10-119`. The footer month changes from March 2026 to April 2026 at the same "
        "point, which suggests a page was replaced during revision without "
        "renumbering. Offset therefore reads 4..5. |",
        "| `s12_cultural_heritage.pdf` | skipped folio | `12-23` is printed on no page: "
        "viewer 23 is `12-22` and viewer 24 is `12-24`. Offset therefore reads 1..2. |",
        "",
        "**Consequence for citations.** A printed folio is not a unique page",
        "identifier: `10-119` refers to two different PDF pages. Any citation must",
        "carry `pdf_page_index` alongside the folio, which is what",
        "`stage1/extract_pages.py` already does. A folio alone is not sufficient.",
        "",
        "## Remaining uncertainties",
        "",
        "1. `absent` means the footer date is present and no folio precedes it. It is",
        "   an observation about the extracted text, not a guarantee that the printed",
        "   page is unnumbered - a folio set in a font PDFKit fails to extract would",
        "   look the same. No such case has been identified, but it is not excluded.",
        "2. Offsets are constant within 32 of 34 chapters. The two exceptions are the",
        "   sequence anomalies above, so offset arithmetic is unsafe for those two",
        "   chapters specifically - and the project never uses it in any case.",
        "3. No PDF in either report carries a `/PageLabels` tree, so the printed folio",
        "   is the only page-label evidence available. Nothing here is inferred from",
        "   the viewer index.",
        "4. `eia_text_sign_page.pdf` has no text at all, so it is `unverified` rather",
        "   than `absent`. It is a sign-off page, not a numbered content page.",
        "",
        "## Effect on the registry",
        "",
        "`stage0/reports.json` keeps `validation_status: incomplete`. This",
        "reconciliation corrects page-number counts; it does not complete Stage 0,",
        "and the deferred map geometry is untouched.",
        "",
    ]

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))

    for reg, s in summary.items():
        print(f"{reg}: {s['mode'][0]} -> {s['mode'][1]} | "
              f"changed chapters {s['changed_chapters']} | "
              f"coverage {s['coverage']}")
    print(f"\nwritten: {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
